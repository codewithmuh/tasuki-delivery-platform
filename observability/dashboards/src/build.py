"""Render the dashboards: generated/<uid>.json, kustomization.yaml and the README's metric table.

    python3 observability/dashboards/src/build.py           # write the files (make dashboards-generate)
    python3 observability/dashboards/src/build.py --check   # fail if any committed file differs (CI)

Output is deterministic (no timestamps, stable key order), so a stale file is a real difference.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import location
import orders
import overview
import promql
import service_red
import simulator
import slos
from grafana import Dashboard
from metrics import BY_NAME, HISTOGRAMS, METRICS

ROOT = Path(__file__).resolve().parent.parent  # observability/dashboards
REPO = ROOT.parent.parent
GENERATED = ROOT / "generated"
KUSTOMIZATION = ROOT / "kustomization.yaml"
README = ROOT / "README.md"
TABLE_START = "<!-- metrics:start (generated by build.py from src/metrics.py; do not edit) -->"
TABLE_END = "<!-- metrics:end -->"
FOLDER = "Tasuki"

MODULES = (overview, service_red, location, orders, slos, simulator)


def dashboards() -> list[Dashboard]:
    return [module.build() for module in MODULES]


def queries(model: dict) -> list[tuple[str, str]]:
    """(where, PromQL) for every query in a dashboard: panel targets, annotations and variable queries."""
    found = []
    for panel in model["panels"]:
        for target in panel.get("targets", []):
            found.append((f"panel '{panel['title']}' {target['refId']}", target["expr"]))
    for annotation in model["annotations"]["list"]:
        found.append((f"annotation '{annotation['name']}'", annotation["expr"]))
    for variable in model["templating"]["list"]:
        if variable["type"] == "query":
            found.append((f"variable ${variable['name']}", promql.variable_selector(variable["query"])))
    return found


def metrics_used(model: dict) -> set[str]:
    names: set[str] = set()
    for _, expr in queries(model):
        names |= {promql.base_name(n, HISTOGRAMS) for n in promql.metric_names(promql.substitute(expr))}
    return names


def render_json(model: dict) -> str:
    return json.dumps(model, indent=2, ensure_ascii=False) + "\n"


def render_kustomization(uids: list[str]) -> str:
    lines = [
        "# Generated by `make dashboards-generate` (observability/dashboards/src/build.py). Do not edit.",
        "# Argo CD syncs this directory into the monitoring namespace; the kube-prometheus-stack Grafana sidecar",
        '# loads every ConfigMap labelled grafana_dashboard: "1", and puts it in the folder named by grafana_folder',
        "# when the sidecar's folderAnnotation is set to grafana_folder.",
        "apiVersion: kustomize.config.k8s.io/v1beta1",
        "kind: Kustomization",
        "namespace: monitoring",
        "generatorOptions:",
        "  disableNameSuffixHash: true",
        "  labels:",
        '    grafana_dashboard: "1"',
        "  annotations:",
        f"    grafana_folder: {FOLDER}",
        "configMapGenerator:",
    ]
    for uid in uids:
        lines += [f"  - name: dashboard-{uid}", "    files:", f"      - generated/{uid}.json"]
    return "\n".join(lines) + "\n"


def _source(name: str) -> str:
    metric = BY_NAME[name]
    if metric.upstream:
        return metric.upstream
    links = ", ".join(f"[{path}](../../{path})" for path in metric.sources)
    if metric.pending:
        links += " (**pending**: the service is being written; name agreed with its owner)"
    return links


def render_table(models: list[dict]) -> str:
    used_in: dict[str, list[str]] = {}
    for model in models:
        for name in metrics_used(model):
            used_in.setdefault(name, []).append(model["title"].removeprefix("Tasuki "))
    rows = [
        "| Metric | Type | Labels used | Source | Dashboards |",
        "|---|---|---|---|---|",
    ]
    for metric in METRICS:
        where = " · ".join(used_in.get(metric.name, [])) or "**unused**"
        rows.append(f"| `{metric.name}` | {metric.kind} | {metric.labels} | {_source(metric.name)} | {where} |")
    return "\n".join(rows)


def render_readme(models: list[dict]) -> str:
    text = README.read_text(encoding="utf-8")
    start, end = text.index(TABLE_START), text.index(TABLE_END)
    return text[: start + len(TABLE_START)] + "\n" + render_table(models) + "\n" + text[end:]


def outputs() -> dict[Path, str]:
    models = [d.to_json() for d in dashboards()]
    files = {GENERATED / f"{m['uid']}.json": render_json(m) for m in models}
    files[KUSTOMIZATION] = render_kustomization([m["uid"] for m in models])
    files[README] = render_readme(models)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed files instead of writing")
    args = parser.parse_args()

    files = outputs()
    stale_json = sorted(set(GENERATED.glob("*.json")) - set(files))
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        stale += stale_json
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}", file=sys.stderr)
        if stale:
            print("Run 'make dashboards-generate' and commit the result.", file=sys.stderr)
            return 1
        print(f"dashboards: {len(files)} generated files are up to date")
        return 0

    for path in stale_json:
        path.unlink()
        print(f"removed {path.relative_to(REPO)}")
    for path, text in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
